"""
Write the frontends' copy of the India states / districts dataset.

    python manage.py india_regions_js ../BookMyVenue-frontend-main/src/constants/indiaRegions.js
    python manage.py india_regions_js ../BookMyVenue-SuperAdmin-main/src/constants/indiaRegions.js

venues/data/india_regions.json is the ONE source (see venues/regions.py). The
customer app and the SuperAdmin app each bundle an identical generated
module, so their dropdowns and search work even against an older deployed
backend. Edit the JSON, then run this for both apps.
"""
import json

from django.core.management.base import BaseCommand

from venues import regions

HEADER = """// GENERATED by the backend: `python manage.py india_regions_js <this file>`
// from venues/data/india_regions.json. Do not edit by hand — edit the JSON
// and regenerate (the customer and SuperAdmin apps carry identical copies).
//
// Every Indian state and union territory with its districts. Each entry:
//   name, code (ISO 3166-2), type ('state' | 'ut'), pinZones (allowed first
//   PIN digits), aliases (older / short names), districts,
//   districtAliases ({ district: [older names] }).
"""


class Command(BaseCommand):
    help = 'Write the frontend copy of the India states/districts dataset (ES module).'

    def add_arguments(self, parser):
        parser.add_argument('path', help='Destination .js file')

    def handle(self, *args, **options):
        data = regions.dataset()
        body = json.dumps(data['states'], ensure_ascii=False, indent=1)
        text = (
            HEADER
            + f"\nexport const INDIA_REGIONS_SOURCE = {json.dumps(data['source'], ensure_ascii=False)};\n"
            + f'\nexport const INDIA_REGIONS = Object.freeze({body});\n'
        )
        with open(options['path'], 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(text)
        total = sum(len(s['districts']) for s in data['states'])
        self.stdout.write(f"Wrote {len(data['states'])} states/UTs, {total} districts to {options['path']}")
